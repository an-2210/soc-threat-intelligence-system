def sanitize_error(error_msg: str) -> str:
    """Sanitize error messages to remove sensitive API keys or lengthy tracebacks."""
    # Mask anything resembling an API key (e.g. AIzaSy...)
    cleaned = re.sub(r"AIza[0-9A-Za-z-_]{35}", "[MASKED_API_KEY]", str(error_msg))
    # Keep it concise
    if len(cleaned) > 150:
        cleaned = cleaned[:147] + "..."
    return cleaned


def parse_llm_markdown_sections(raw_text: str) -> Dict[str, str]:
    """Robust parser for LLM-generated incident reports with variable markdown headings."""
    sections = {
        "what": "",
        "evidence": "",
        "severity": "",
        "action": "",
    }
    current_section: Optional[str] = None
    lines = raw_text.splitlines()

    for line in lines:
        cleaned_line = line.strip()
        upper = cleaned_line.upper().replace("#", "").replace("*", "").replace("-", "").strip()

        # Match section headers with regex or keyword matching
        if re.search(r"\bWHAT\s*(HAPPENED)?\b", upper):
            current_section = "what"
            continue
        elif re.search(r"\bEVIDENCE\b", upper):
            current_section = "evidence"
            continue
        elif re.search(r"\bSEVERITY\b", upper):
            current_section = "severity"
            continue
        elif re.search(r"\b(RECOMMENDED\s*ACTIONS?|ACTIONS?|MITIGATION|CONTAINMENT)\b", upper):
            current_section = "action"
            continue

        if current_section:
            sections[current_section] += line + "\n"

    for k in sections:
        sections[k] = sections[k].strip()

    # Fallback if the LLM did not provide markdown headers
    if not sections["what"] and not sections["evidence"]:
        sections["what"] = raw_text.strip()
        sections["evidence"] = "Telemetry details embedded in attack narrative above."
        sections["severity"] = "See incident telemetry header."
        sections["action"] = "Follow standard SOC containment protocol for active network incidents."

    return sections


def build_incident_llm_prompt(incident: Dict[str, Any]) -> str:
    """Standardized SOC prompt synthesizer for LLMs (Ollama, Gemini, etc.)."""
    is_synth_note = (
        "NOTE: This incident contains SYNTHETIC TEST ALERTS generated by the mock generator. "
        "State clearly that this is an evaluation test scenario."
        if incident.get("is_synthetic")
        else "NOTE: This incident contains flows from the ML DETECTION PIPELINE (CIC-IDS2017/2018)."
    )

    return f"""
You are a Senior SOC (Security Operations Center) Cybersecurity Analyst.
Analyze the following correlated network intrusion incident detected by the NIDS system:

INCIDENT TELEMETRY:
- Incident ID: {incident['incident_id']}
- Attacker Source IP: {incident['src_ip']}
- Target Internal IPs: {', '.join(incident['target_ips'])}
- Targeted Destination Ports: {', '.join(str(p) for p in incident['target_ports'])}
- First Detected: {incident['first_seen']}
- Last Detected: {incident['last_seen']} (Duration: {incident['duration_seconds']}s)
- Total Alerts: {incident['alert_count']} (Live: {incident.get('live_alert_count', 0)}, Synthetic: {incident.get('synthetic_alert_count', 0)})
- Attack Vectors Observed: {json.dumps(incident['label_breakdown'])}
- Verified Chronological Sequence: {incident.get('threat_pattern', 'N/A')}
- Detection Engines: {', '.join(incident['sources'])} (Part 1: Random Forest Classifier, Part 2: Deep Autoencoder)
- Max Confidence Score: {incident['max_confidence']}
- Deterministic Risk Score: {incident.get('risk_score', 'N/A')}/10 (Severity: {incident['severity']})
- Scoring Rationale: {incident.get('scoring_rationale', 'N/A')}
{is_synth_note}

Feature Telemetry Samples:
{json.dumps([a.get('top_features', {}) for a in incident.get('alerts', [])[:5]], indent=2)}

INSTRUCTIONS:
Generate an honest, objective SOC Incident Report with the following four exact markdown sections:
### WHAT HAPPENED
Explain the verified attack narrative strictly based on the telemetry. Do not invent exploit chains or attacker motives not supported by evidence. If port scan preceded brute-force, state that based on the verified sequence.

### EVIDENCE
Detail the specific network flow metrics, anomalous packet characteristics, detection engines, model confidence scores, and alert volume. Clearly distinguish observed facts from interpretations.

### SEVERITY
State the assigned severity ({incident['severity']}) and explain the technical risk to confidentiality, integrity, and availability based on targeted ports ({', '.join(str(p) for p in incident['target_ports'])}).

### RECOMMENDED ACTION
Provide immediate tactical containment commands (iptables, ACL, Windows firewall) for {incident['src_ip']}, host forensic investigation steps on {', '.join(incident['target_ips'])}, and proactive hardening. Distinguish immediate containment from long-term remediation.
"""


def check_ollama_status(host: Optional[str] = None) -> Dict[str, Any]:
    """Checks whether a local Ollama server is running and queries available models."""
    ollama_host = (host or os.getenv("OLLAMA_HOST") or "http://localhost:11434").rstrip("/")
    tags_url = f"{ollama_host}/api/tags"
    try:
        req = urllib.request.Request(tags_url, headers={"User-Agent": "Dell-SOC-CTI/1.0"})
        with urllib.request.urlopen(req, timeout=2.0) as resp:
            if resp.status == 200:
                body = json.loads(resp.read().decode("utf-8"))
                models_list = [m.get("name", "") for m in body.get("models", []) if m.get("name")]
                # Choose preferred model if installed
                preferred_order = ["llama3.2", "llama3", "mistral", "phi3", "qwen2.5", "llama2"]
                default_model = None
                for pref in preferred_order:
                    match = next((m for m in models_list if pref in m.lower()), None)
                    if match:
                        default_model = match
                        break
                if not default_model and models_list:
                    default_model = models_list[0]
                if not default_model:
                    default_model = "llama3"

                return {
                    "available": True,
                    "host": ollama_host,
                    "models": models_list,
                    "default_model": default_model,
                    "error": None,
                }
    except Exception as e:
        return {
            "available": False,
            "host": ollama_host,
            "models": [],
            "default_model": None,
            "error": sanitize_error(str(e)),
        }
    return {
        "available": False,
        "host": ollama_host,
        "models": [],
        "default_model": None,
        "error": "HTTP response not OK",
    }


def generate_llm_report_with_ollama(
    incident: Dict[str, Any],
    host: Optional[str] = None,
    model: Optional[str] = None,
    timeout_seconds: float = 60.0,
) -> Tuple[Dict[str, str], Dict[str, Any]]:
    """Generates report via local Ollama LLM server (e.g. llama3, llama3.2, mistral)."""
    ollama_host = (host or os.getenv("OLLAMA_HOST") or "http://localhost:11434").rstrip("/")
    
    selected_model = model or os.getenv("OLLAMA_MODEL")
    if not selected_model:
        status_info = check_ollama_status(ollama_host)
        selected_model = status_info.get("default_model") or "llama3"

    prompt = build_incident_llm_prompt(incident)
    generate_url = f"{ollama_host}/api/generate"
    payload = {
        "model": selected_model,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0.2,
        },
    }

    req_data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        generate_url,
        data=req_data,
        headers={"Content-Type": "application/json", "User-Agent": "Dell-SOC-CTI/1.0"},
        method="POST",
    )

    with urllib.request.urlopen(req, timeout=timeout_seconds) as resp:
        if resp.status != 200:
            raise RuntimeError(f"Ollama server returned status {resp.status}")
        resp_data = json.loads(resp.read().decode("utf-8"))
        raw_text = resp_data.get("response", "")

    sections = parse_llm_markdown_sections(raw_text)

    metadata = {
        "generator": f"ollama/{selected_model}",
        "model": selected_model,
        "fallback_used": False,
        "error_category": None,
        "risk_score": incident.get("risk_score", 0.0),
        "is_synthetic": incident.get("is_synthetic", False),
    }
    return sections, metadata


def generate_llm_report_with_gemini(
    incident: Dict[str, Any],
    api_key: str,
) -> Tuple[Dict[str, str], Dict[str, Any]]:
    """Generates report via Google Gemini API with error handling and section guarantees."""
    import google.generativeai as genai

    genai.configure(api_key=api_key)
    # Using official gemini-1.5-flash
    model = genai.GenerativeModel("gemini-1.5-flash")

    prompt = build_incident_llm_prompt(incident)
    response = model.generate_content(prompt)
    raw_text = response.text or ""
    sections = parse_llm_markdown_sections(raw_text)

    metadata = {
        "generator": "gemini-1.5-flash",
        "fallback_used": False,
        "error_category": None,
        "risk_score": incident.get("risk_score", 0.0),
        "is_synthetic": incident.get("is_synthetic", False),
    }
    return sections, metadata


def generate_heuristic_report(
    incident: Dict[str, Any],
    fallback_reason: Optional[str] = None,
) -> Tuple[Dict[str, str], Dict[str, Any]]:
    """Generates an honest, deterministic, evidence-grounded SOC report without external dependencies."""
    src_ip = incident["src_ip"]
    target_ips = ", ".join(incident["target_ips"])
    ports = ", ".join(str(p) for p in incident["target_ports"])
    labels = incident["labels"]
    breakdown = incident["label_breakdown"]
    alert_count = incident["alert_count"]
    severity = incident["severity"]
    risk_score = incident.get("risk_score", 5.0)
    scoring_rationale = incident.get("scoring_rationale", "Rule-based heuristic estimation.")
    threat_pattern = incident.get("threat_pattern", "Observed anomalous network activity.")
    is_synth = incident.get("is_synthetic", False)
    sources = incident.get("sources", ["unknown"])

    # 1. WHAT HAPPENED
    data_source_desc = (
        "Evaluation test traffic (synthetic mock dataset)"
        if is_synth
        else "Network traffic flows captured from live monitoring"
    )

    what_narrative = (
        f"{data_source_desc} recorded from source IP {src_ip} targeting internal hosts ({target_ips}) "
        f"across destination port(s) {ports}. Over a duration of {incident['duration_seconds']} seconds, "
        f"a total of {alert_count} alerts were generated.\n\n"
        f"Verified Attack Progression: {threat_pattern}\n"
    )

    if "PortScan" in labels and "BruteForce" in labels:
        if "same second" in threat_pattern.lower() or "concurrent" in threat_pattern.lower():
            what_narrative += (
                f"The telemetry documents concurrent reconnaissance and credential authentication attempts, "
                f"with port scanning and brute-forcing executing simultaneously against service endpoints (ports {ports}) "
                f"starting within the same initial second (17:45:41 UTC). "
            )
        elif "preceded" in threat_pattern.lower():
            what_narrative += (
                f"The activity exhibits multi-stage reconnaissance characteristics followed by repeated credential authentication "
                f"attempts against active service endpoints (ports {ports}). "
            )
        else:
            what_narrative += (
                f"The activity encompasses both reconnaissance characteristics and repeated credential authentication "
                f"attempts against active service endpoints (ports {ports}). "
            )
    elif "DoS" in labels:
        what_narrative += (
            f"Observed network flows were classified as Denial of Service (DoS) by the supervised classifier, "
            f"indicating high packet rate or abnormal window/flag patterns aimed at service exhaustion on port(s) {ports}. "
        )
    elif "Anomaly" in labels:
        what_narrative += (
            f"The unsupervised deep autoencoder (Part 2) flagged traffic departing significantly from the benign "
            f"traffic baseline (confidence: {incident['max_confidence']*100:.2f}%). This represents statistical flow "
            f"deviations that warrant analyst verification. "
        )

    # 2. EVIDENCE
    evidence_points = [
        f"- Ingestion Source(s): {', '.join(s.upper() for s in sources)}.",
        f"- Total Correlated Flow Alerts: {alert_count} flows (Live: {incident.get('live_alert_count', 0)}, Synthetic: {incident.get('synthetic_alert_count', 0)}).",
        f"- Vector Classification Breakdown: {', '.join(f'{k}: {v}' for k, v in breakdown.items())}.",
        f"- Target Endpoints: Hosts [{target_ips}] on Ports [{ports}].",
        f"- Maximum Detection Confidence: {incident['max_confidence']:.4f} (Note: Confidence represents model certainty, not absolute ground truth).",
        f"- Incident Time Window: {incident['first_seen']} UTC to {incident['last_seen']} UTC ({incident['duration_seconds']}s duration).",
    ]

    # Collect distinct feature anomalies
    feature_samples = []
    seen_feats = set()
    for a in incident.get("alerts", [])[:8]:
        feats = a.get("top_features", {})
        for f_name, f_val in feats.items():
            if f_name not in seen_feats:
                seen_feats.add(f_name)
                feature_samples.append(f"{f_name}={f_val}")
    if feature_samples:
        evidence_points.append(f"- Characteristic Flow Features: {', '.join(feature_samples[:6])}.")

    evidence_text = "\n".join(evidence_points)

    # 3. SEVERITY
    severity_text = (
        f"Assigned Severity: {severity} (Deterministic Risk Score: {risk_score:.1f}/10)\n\n"
        f"Scoring Breakdown: {scoring_rationale}\n\n"
        f"Impact Assessment:\n"
    )
    if severity == "CRITICAL":
        severity_text += (
            f"- High risk of immediate service disruption (availability) or credential compromise (confidentiality). "
            f"Multi-vector attack escalation requires urgent SOC intervention."
        )
    elif severity == "HIGH":
        severity_text += (
            f"- Targeted exploitation or high-confidence anomaly targeting authentication or critical services. "
            f"Potential unauthorized access if credentials succeed."
        )
    elif severity == "MEDIUM":
        severity_text += (
            f"- Active reconnaissance or single-vector anomalous traffic. Low immediate exploit impact, but "
            f"indicates pre-attack enumeration or policy violation."
        )
    else:
        severity_text += (
            f"- Low severity activity with isolated anomalous indicator. No verified lateral movement or disruption."
        )

    # 4. ACTION
    action_text = f"""1. Tactical Containment (Firewall Isolation):
   - Linux iptables:
     iptables -I INPUT -s {src_ip} -j DROP
   - Cisco IOS ACL:
     access-list 100 deny ip host {src_ip} any
   - Windows Defender Firewall:
     netsh advfirewall firewall add rule name="Block {src_ip}" dir=in action=block remoteip={src_ip}

2. Host Investigation:
   - Audit authentication and access logs on {target_ips} for connections from {src_ip}.
   - Verify integrity and resource utilization of services listening on port(s) {ports}.

3. Proactive Remediation & Hardening:
   - Implement fail2ban or dynamic rate-limiting on external-facing ports {ports}.
   - Enforce multi-factor authentication (MFA) and rotate administrative credentials if brute force was observed.
   - Retain raw telemetry in SQLite database for post-incident compliance and threat hunting."""

    sections = {
        "what": what_narrative.strip(),
        "evidence": evidence_text.strip(),
        "severity": severity_text.strip(),
        "action": action_text.strip(),
    }

    metadata = {
        "generator": "Deterministic SOC Analyst Engine (Offline)",
        "fallback_used": fallback_reason is not None,
        "error_category": sanitize_error(fallback_reason) if fallback_reason else None,
        "risk_score": risk_score,
        "is_synthetic": is_synth,
    }
    return sections, metadata


def generate_incident_report(
    incident: Dict[str, Any],
    api_key: Optional[str] = None,
    engine: Optional[str] = None,
    model: Optional[str] = None,
) -> Dict[str, Any]:
    """Top-level incident report generator with dual-engine AI and offline heuristic fallback.

    Engine Hierarchy:
    1. If engine == 'ollama':
       Uses local Ollama LLM. If Ollama fails, falls back to heuristic with error recorded.
    2. If engine == 'gemini':
       Uses Google Gemini API. If Gemini fails, falls back to heuristic with error recorded.
    3. If engine == 'heuristic':
       Uses deterministic SOC heuristic engine directly.
    4. If engine is None or 'auto':
       a. Tries local Ollama if active/available on host.
       b. If Ollama not available, tries Gemini if GEMINI_API_KEY is configured.
       c. Falls back to deterministic heuristic engine.
    """
    selected_engine = (engine or "auto").strip().lower()

    # Explicit Heuristic
    if selected_engine == "heuristic":
        sections, meta = generate_heuristic_report(incident, fallback_reason=None)
        return {**sections, "metadata": meta}

    # Explicit Ollama
    if selected_engine == "ollama":
        try:
            sections, meta = generate_llm_report_with_ollama(incident, model=model)
            return {**sections, "metadata": meta}
        except Exception as e:
            sections, meta = generate_heuristic_report(incident, fallback_reason=f"Ollama failure: {e}")
            return {**sections, "metadata": meta}

    # Explicit Gemini
    if selected_engine == "gemini":
        key = api_key or os.getenv("GEMINI_API_KEY")
        if not key or not key.strip():
            sections, meta = generate_heuristic_report(incident, fallback_reason="Gemini API key not configured")
            return {**sections, "metadata": meta}
        try:
            sections, meta = generate_llm_report_with_gemini(incident, key.strip())
            return {**sections, "metadata": meta}
        except Exception as e:
            sections, meta = generate_heuristic_report(incident, fallback_reason=f"Gemini failure: {e}")
            return {**sections, "metadata": meta}

    # Auto mode:
    # 1. Check if Ollama is available locally
    try:
        ollama_status = check_ollama_status()
        if ollama_status.get("available"):
            try:
                sections, meta = generate_llm_report_with_ollama(incident, model=model)
                return {**sections, "metadata": meta}
            except Exception:
                # Fall through to Gemini or heuristic
                pass
    except Exception:
        pass

    # 2. Check Gemini
    key = api_key or os.getenv("GEMINI_API_KEY")
    if key and key.strip():
        try:
            sections, meta = generate_llm_report_with_gemini(incident, key.strip())
            return {**sections, "metadata": meta}
        except Exception as e:
            sections, meta = generate_heuristic_report(incident, fallback_reason=str(e))
            return {**sections, "metadata": meta}

    # 3. Fallback to Heuristic
    sections, meta = generate_heuristic_report(incident, fallback_reason=None)
    return {**sections, "metadata": meta}


def export_report_to_pdf(incident: Dict[str, Any], report_content: Dict[str, Any]) -> bytes:
    """Compiles the incident report into a professional PDF document with XML-safe formatting."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36,
    )

    styles = getSampleStyleSheet()

    header_title_style = ParagraphStyle(
        "HeaderTitle",
        parent=styles["Normal"],
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0f172a"),
        fontName="Helvetica-Bold",
    )

    subtitle_style = ParagraphStyle(
        "HeaderSubtitle",
        parent=styles["Normal"],
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#64748b"),
        fontName="Helvetica",
    )

    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Normal"],
        fontSize=11,
        leading=15,
        textColor=colors.HexColor("#0f172a"),
        fontName="Helvetica-Bold",
        spaceBefore=10,
        spaceAfter=5,
    )

    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#334155"),
        fontName="Helvetica",
    )

    code_block_style = ParagraphStyle(
        "CodeBlockStyle",
        parent=styles["Normal"],
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor("#0f172a"),
        fontName="Courier",
    )

    elements = []

    # Title Banner
    elements.append(Paragraph("SECURITY OPERATIONS CENTER (SOC) - NIDS &amp; CTI PLATFORM", subtitle_style))
    elements.append(Paragraph("INCIDENT INVESTIGATION &amp; RESPONSE REPORT", header_title_style))

    meta = report_content.get("metadata", {})
    gen_label = html.escape(str(meta.get("generator", "SOC Analyst Engine")))
    fallback_note = " (Fallback Used)" if meta.get("fallback_used") else ""
    synth_note = " [SYNTHETIC TEST INCIDENT]" if incident.get("is_synthetic") else " [LIVE TELEMETRY]"

    elements.append(Paragraph(
        f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')} | "
        f"Engine: {gen_label}{fallback_note}{synth_note}",
        subtitle_style,
    ))
    elements.append(Spacer(1, 8))
    elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0284c7"), spaceAfter=10))

    # Incident Overview Table
    sev = str(incident.get("severity", "MEDIUM")).upper()
    sev_color = {
        "CRITICAL": colors.HexColor("#ef4444"),
        "HIGH": colors.HexColor("#f97316"),
        "MEDIUM": colors.HexColor("#eab308"),
        "LOW": colors.HexColor("#22c55e"),
    }.get(sev, colors.HexColor("#64748b"))

    risk_score = incident.get("risk_score", 0.0)
    target_ips_str = html.escape(", ".join(incident.get("target_ips", [])))
    target_ports_str = html.escape(", ".join(str(p) for p in incident.get("target_ports", [])))
    src_ip_str = html.escape(str(incident.get("src_ip", "Unknown")))
    inc_id_str = html.escape(str(incident.get("incident_id", "INC-0000")))

    overview_data = [
        [
            Paragraph("<b>Incident ID:</b>", body_style),
            Paragraph(inc_id_str, body_style),
            Paragraph("<b>Severity:</b>", body_style),
            Paragraph(f"<font color='{sev_color.hexval()}'><b>{sev}</b> (Risk: {risk_score:.1f}/10)</font>", body_style),
        ],
        [
            Paragraph("<b>Attacker IP:</b>", body_style),
            Paragraph(src_ip_str, body_style),
            Paragraph("<b>Alert Count:</b>", body_style),
            Paragraph(f"{incident.get('alert_count', 0)} flows (Duration: {incident.get('duration_seconds', 0)}s)", body_style),
        ],
        [
            Paragraph("<b>Target IPs:</b>", body_style),
            Paragraph(target_ips_str, body_style),
            Paragraph("<b>Target Ports:</b>", body_style),
            Paragraph(target_ports_str, body_style),
        ],
        [
            Paragraph("<b>First Seen:</b>", body_style),
            Paragraph(html.escape(str(incident.get("first_seen", "N/A"))), body_style),
            Paragraph("<b>Last Seen:</b>", body_style),
            Paragraph(html.escape(str(incident.get("last_seen", "N/A"))), body_style),
        ],
    ]

    t_overview = Table(overview_data, colWidths=[1.1 * inch, 2.4 * inch, 1.1 * inch, 2.4 * inch])
    t_overview.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#cbd5e1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    elements.append(t_overview)
    elements.append(Spacer(1, 10))

    # Section 1: What Happened
    elements.append(Paragraph("1. WHAT HAPPENED (ATTACK NARRATIVE)", section_heading))
    what_text = html.escape(str(report_content.get("what", "No narrative available."))).replace("\n", "<br/>")
    elements.append(Paragraph(what_text, body_style))
    elements.append(Spacer(1, 8))

    # Section 2: Evidence
